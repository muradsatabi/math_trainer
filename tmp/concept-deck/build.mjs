function txt(s, value, x, y, w, h, opts={}) {
  const a = s.shapes.add({
    name: opts.name ?? String(value).slice(0,55), geometry:"textbox",
    position:{left:x,top:y,width:w,height:h}, fill:opts.fill??"none", line:noLine
  });
  a.text = value;
  a.text.style = {
    typeface:font, fontSize:opts.size??25, color:opts.color??c.ink, bold:opts.bold??false,
    alignment:opts.align??"left", verticalAlignment:opts.valign??"top",
    insets:opts.insets??0, autoFit:"none", wrap:opts.wrap??"square"
  };
  return a;
}

function slide(id, section, heading, note="", dark=false){
  const s=deck.slides.add();
  s.background.fill=dark?c.night:c.paper;
  registry.push({id,section,heading,s,dark});
  s.speakerNotes.text=[note,concept,hub].filter(Boolean).join("\n\n");
  if(section) txt(s,section.toUpperCase(),64,40,1110,25,{size:17,bold:true,color:dark?c.mint:c.teal});
  if(heading) txt(s,heading,64,81,1150,100,{size:47,bold:true,color:dark?c.white:c.ink});
  return s;
}

function jump(s,caption,to,x,y,w,h,opts={}){
  const key="nav_"+links.length;
  txt(s,caption,x,y,w,h,{name:key,size:opts.size??19,bold:true,fill:opts.fill??c.cloud,
    color:opts.color??c.teal,align:opts.align??"center",valign:"middle",insets:{left:10,right:10,top:0,bottom:0}});
  links.push({slide:registry.findIndex(v=>v.s===s)+1,key,to});
}

function rows(s, items, y=185, step=100, labelWidth=280, dark=false){
  items.forEach(([label,detail],i)=>{
    const at=y+i*step;
    txt(s,label,64,at,labelWidth,step-8,{size:27,bold:true,color:dark?c.mint:c.teal});
    txt(s,detail,64+labelWidth+30,at,1152-labelWidth-30,step-8,{size:25,color:dark?c.white:c.ink});
  });
}

function columns(s, parts, y=190){
  const gap=40;
  const width=(1152-gap*(parts.length-1))/parts.length;
  parts.forEach(([label,detail],i)=>{
    const x=64+i*(width+gap);
    txt(s,label,x,y,width,100,{size:32,bold:true,color:c.teal});
    txt(s,detail,x,y+112,width,220,{size:25});
  });
}

function takeaway(s,text,y=560,dark=false){
  txt(s,text,64,y,1152,65,{size:22,bold:true,color:dark?c.mint:c.teal});
}

