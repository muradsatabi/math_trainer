class LessonSection {
  const LessonSection(this.title, this.text, [this.formula]);
  final String title, text;
  final String? formula;
}

class DemoTopicLesson {
  const DemoTopicLesson(this.title, this.idea, this.sections);
  final String title, idea;
  final List<LessonSection> sections;

  static DemoTopicLesson forTopic(String topicId, String operation) {
    if (topicId == 'literal_common_factor') return literalFactor;
    if (topicId == 'literal_bracket_multiplication') return literalExpansion;
    if (operation == 'expand') return numericExpansion;
    return numericFactor;
  }

  static const numericFactor = DemoTopicLesson(
    'Выносим численный общий множитель',
    'Число перед скобкой умножает всё, что внутри. Вынести множитель — '
        'значит найти общий множитель у всех слагаемых и записать его один раз перед скобкой. '
        'Значение выражения при этом сохраняется.',
    [
      LessonSection(
        '1. Что означает запись',
        '6x означает 6 · x. В выражении 6x + 9 два слагаемых: 6x и 9. '
            'Мы ищем число, на которое можно разделить каждое из них.',
      ),
      LessonSection(
        '2. Откуда берётся число перед скобкой',
        'И 6, и 9 делятся на 3 без остатка. Поэтому в этом примере удобно вынести 3. '
            'Представим каждое слагаемое как произведение с этой тройкой.',
        '6x = 3 · 2x\n9 = 3 · 3',
      ),
      LessonSection(
        '3. Откуда берётся содержимое скобки',
        'Каждое исходное слагаемое делим на вынесенное число. '
            'После деления 6x на 3 остаётся 2x, после деления 9 на 3 остаётся 3. '
            'Именно эти остатки записываем в скобках. Знак плюс сохраняем.',
        '6x : 3 = 2x\n9 : 3 = 3\n6x + 9 = 3(2x + 3)',
      ),
      LessonSection(
        '4. Почему это работает',
        'Слева у нас два произведения с одинаковым множителем 3. '
            'Справа тройка записана один раз, но по-прежнему умножает оба слагаемых.',
        '3 · 2x + 3 · 3 = 3(2x + 3)',
      ),
      LessonSection(
        '5. Проверяем обратным действием',
        'Умножим число перед скобкой на каждое слагаемое внутри. '
            'Должно в точности получиться исходное выражение.',
        '3(2x + 3) = 3 · 2x + 3 · 3 = 6x + 9',
      ),
      LessonSection(
        '6. Где легко запутаться',
        'Если записать 3(2x + 9), получится 6x + 27: второе слагаемое забыли разделить. '
            'Делим все слагаемые, а не только первое. Если слагаемое равно вынесенному множителю, '
            'внутри остаётся 1, а не 0.',
        '3x + 3 = 3(x + 1)',
      ),
      LessonSection(
        '7. Если слагаемых больше или есть минус',
        'Смысл тот же: делим каждое слагаемое на один и тот же положительный множитель '
            'и сохраняем знаки. Не останавливаемся после первого или второго слагаемого.',
        '6x − 9y + 3 = 3(2x − 3y + 1)',
      ),
    ],
  );

  static const literalFactor = DemoTopicLesson(
    'Выносим буквенный общий множитель',
    'Буква — тоже множитель. Например, a² означает a · a. '
        'Если одинаковая буква или произведение есть в каждом слагаемом, '
        'его можно записать перед скобкой один раз.',
    [
      LessonSection(
        '1. Сначала увидим множители',
        'Разберём 6a² + 9ab. В первом слагаемом две буквы a, во втором — a и b. '
            'Одна a есть в обоих слагаемых. У чисел 6 и 9 есть общий множитель 3.',
        '6a² = 3 · a · 2 · a\n9ab = 3 · a · 3 · b',
      ),
      LessonSection(
        '2. Что можно вынести',
        'Общая часть обоих произведений — 3 · a. Запишем её перед скобкой как 3a. '
            'Букву b вынести нельзя: в первом слагаемом её нет.',
        '6a² + 9ab = 3a(…)',
      ),
      LessonSection(
        '3. Что остаётся от первого слагаемого',
        'Из произведения 3 · a · 2 · a забираем общую часть 3 · a. '
            'Остаётся 2 · a, то есть 2a. У a² было два множителя a, один вынесли, один остался.',
        '6a² = 3a · 2a',
      ),
      LessonSection(
        '4. Что остаётся от второго слагаемого',
        'Из 3 · a · 3 · b забираем ту же общую часть 3 · a. '
            'Остаётся 3 · b. Записываем оба остатка со знаком плюс.',
        '9ab = 3a · 3b\n6a² + 9ab = 3a(2a + 3b)',
      ),
      LessonSection(
        '5. Проверяем возвращением к началу',
        'Умножаем 3a на каждое слагаемое скобки. '
            'При a · a получается a², а при a · b получается ab. '
            'Ни одна буква не должна исчезнуть или появиться без причины.',
        '3a · 2a = 6a²\n3a · 3b = 9ab',
      ),
      LessonSection(
        '6. Если внутри остаётся единица',
        'Когда исходное слагаемое целиком совпадает с вынесенным множителем, '
            'остаток равен 1. Ведь 3a · 1 = 3a. Удалять это слагаемое нельзя.',
        '3a² + 3a = 3a(a + 1)',
      ),
      LessonSection(
        '7. Для нескольких букв, степеней и скобок',
        'Общая часть должна быть в каждом слагаемом. '
            'В степенях берём лишь столько одинаковых множителей, сколько есть у всех: '
            'у a³ и a² общими могут быть две a. Целую скобку тоже можно считать множителем, '
            'но только если это одна и та же скобка в каждом произведении.',
        'a³ + a²b = a²(a + b)\n2a(x + 1) + 3b(x + 1) = (x + 1)(2a + 3b)',
      ),
    ],
  );

  static const numericExpansion = DemoTopicLesson(
    'Умножаем число на скобку',
    'Скобка объединяет несколько слагаемых. Число перед скобкой относится '
        'ко всей скобке: на него нужно умножить каждое слагаемое внутри.',
    [
      LessonSection(
        '1. Что означает число перед скобкой',
        '3(x + 2) можно представить как три одинаковых набора. '
            'В каждом наборе есть x и ещё 2. Значит, всего три x и три двойки.',
        '3(x + 2) = (x + 2) + (x + 2) + (x + 2) = 3x + 6',
      ),
      LessonSection(
        '2. Разберём пример посложнее',
        'В скобке 2x + 4 − y три слагаемых со своими знаками. '
            'Тройка должна умножить все три: 2x, 4 и −y.',
        '3(2x + 4 − y)',
      ),
      LessonSection(
        '3. Первое произведение',
        'У 2x числовой множитель 2. Умножаем 3 на 2, получаем 6; буква x остаётся. '
            'Здесь мы не складываем 3 и 2: перед скобкой стоит умножение.',
        '3 · 2x = 6x',
      ),
      LessonSection(
        '4. Второе и третье произведения',
        '3 · 4 даёт 12. Последнее слагаемое −y означает −1 · y. '
            'Положительная тройка, умноженная на −y, даёт −3y.',
        '3 · 4 = 12\n3 · (−y) = −3y',
      ),
      LessonSection(
        '5. Собираем ответ',
        'Записываем все полученные слагаемые с их знаками. '
            'Скобка раскрыта, когда внешний множитель применён к каждому её слагаемому.',
        '3(2x + 4 − y) = 6x + 12 − 3y',
      ),
      LessonSection(
        '6. Проверяем, ничего ли не забыли',
        'До сложения подобных слагаемых каждому исходному слагаемому должно '
            'соответствовать произведение. В записи 6x + 4 − y тройка умножила '
            'только первое слагаемое — 4 и −y остались без умножения. '
            'Для нашего примера можно дополнительно взять x = 1, y = 1: '
            'с обеих сторон получится 15. Одна такая проверка помогает заметить ошибку, '
            'но сама по себе не доказывает равенство для всех букв.',
      ),
      LessonSection(
        '7. Если есть вложенная скобка',
        'Удобно сначала раскрыть внутреннюю скобку, затем внешнюю, '
            'и в конце сложить числовые слагаемые. Каждый раз действует то же правило.',
        '2(3(x + 1) + 4) = 2(3x + 3 + 4)\n= 2(3x + 7) = 6x + 14',
      ),
    ],
  );

  static const literalExpansion = DemoTopicLesson(
    'Умножаем буквенный множитель на скобку',
    'Правило такое же, как с числом: внешний множитель умножает каждое слагаемое. '
        'Теперь отдельно следим и за числами, и за буквами.',
    [
      LessonSection(
        '1. Разберём смысл записи',
        'В 2a(3a + 2b − 1) внешний множитель — всё произведение 2a. '
            'Внутри три слагаемых. Для каждого нужно использовать и 2, и a.',
        '2a(3a + 2b − 1)',
      ),
      LessonSection(
        '2. Умножаем первое слагаемое',
        'Числа 2 и 3 дают 6. Буква a снаружи умножается на a внутри. '
            'Две одинаковые буквы в произведении — это квадрат. '
            'a · a = a², а не 2a: 2a получается при сложении a + a.',
        '2a · 3a = 2 · 3 · a · a = 6a²',
      ),
      LessonSection(
        '3. Умножаем второе слагаемое',
        'Числа 2 и 2 дают 4. Буквы разные: a · b записывается ab. '
            'В одну букву или квадрат их объединять нельзя.',
        '2a · 2b = 4ab',
      ),
      LessonSection(
        '4. Не теряем последнее слагаемое',
        'Умножение на −1 меняет знак всего множителя 2a. '
            'Буква остаётся, ведь a · 1 = a.',
        '2a · (−1) = −2a',
      ),
      LessonSection(
        '5. Записываем итог',
        'Все три произведения записываем вместе. '
            '6a², 4ab и −2a имеют разные буквенные части, поэтому складывать их '
            'коэффициенты в одно слагаемое нельзя.',
        '2a(3a + 2b − 1) = 6a² + 4ab − 2a',
      ),
      LessonSection(
        '6. Проверяем числа и буквы',
        'Для каждого слагаемого спроси себя: умножил ли я оба числовых множителя, '
            'сохранил ли все буквы, правильно ли поставил знак? '
            'Запись 6a² + 2b − 1 показывает, что умножили только первое слагаемое. '
            'Можно дополнительно подставить a = 1, b = 1: обе правильные записи дают 8. '
            'Одна подстановка — проверка на возможную ошибку, а не доказательство для всех значений.',
